/* FinStudio — make every master-curriculum topic a real lesson route.
   This is a compatibility bridge for the vanilla Pages renderer. It reuses
   any existing topic-specific lesson generated by topic-lessons.js, gives
   every curriculum occurrence a unique route, and supplies a safe fallback
   lesson when a topic has no generated entry. */
(function () {
  "use strict";
  var LS = window.LS = window.LS || {};
  LS.lessons = LS.lessons || {};
  if (!LS.curriculumMap) return;

  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;")
      .replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }
  function slug(s) {
    return String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  }
  function uniqueId(level, module, title) {
    return "topic-l" + level + "-" + slug(module) + "-" + slug(title);
  }
  function findExisting(title) {
    var keys = Object.keys(LS.lessons);
    for (var i = 0; i < keys.length; i++) {
      var lesson = LS.lessons[keys[i]];
      if (lesson && lesson.title === title) return lesson;
    }
    return null;
  }
  function fallbackLesson(id, title, module, level) {
    var simple = title.toLowerCase();
    var definition = "the finance idea called " + title + " and how it is used in decision-making, analysis or modelling.";
    var formula = "Start with the definition → identify the inputs → apply the relevant relationship → interpret the result.";
    if (/margin|ratio|return|multiple|yield|rate|turnover|coverage|moic|irr|beta|alpha|sharpe|peg/.test(simple)) {
      formula = "Metric = Relevant numerator ÷ Relevant denominator\nInterpret the number in context: compare it with history, peers and the underlying economics.";
    } else if (/value|valuation|price|revenue|profit|cash|debt|equity|cost|capital/.test(simple)) {
      formula = "Value / outcome = economic drivers × assumptions\nChange one driver at a time and explain why the result moves.";
    }
    return {
      id: id,
      minutes: 7,
      title: title,
      short: title,
      desc: "A simple, practice-first lesson on " + title + " for Level " + level + ".",
      lede: "Understand " + title + " from first principles, then use it on a realistic finance problem.",
      body: [
        { t: "h2", text: "What is this?" },
        { t: "p", h: esc(definition) },
        { t: "h2", text: "Why does it matter?" },
        { t: "p", h: esc("You will see " + title + " in " + module + ". The goal is not to memorise a definition; it is to know what changes the number, where it appears, and what decision it helps you make.") },
        { t: "h2", text: "How it works" },
        { t: "p", h: esc("1. Identify what the concept measures.<br><br>2. Separate the inputs from the output.<br><br>3. Calculate it consistently.<br><br>4. Interpret the result and ask what could make it misleading.") },
        { t: "formula", title: "Core relationship", lines: [esc(formula)] },
        { t: "example", h: "<p><strong>Real-world example.</strong> Imagine you are reviewing a growing Indian business. You observe " + esc(title) + " in its accounts or valuation work. Start with the company's reported numbers, calculate the measure, then ask whether the change came from volume, price, margins, financing, timing or an assumption.</p><p><strong>What it means:</strong> a finance metric is useful only when you can explain both the number and the business reason behind it.</p>" },
        { t: "h2", text: "Practice" },
        { t: "practice", items: [
          { q: "Explain " + esc(title) + " in your own words as if you were teaching a friend who has never studied finance.", a: "Start with what it measures, name the main inputs, and finish with why an investor, manager or banker would care." },
          { q: "Give one situation where " + esc(title) + " could improve while the underlying business economics do not.", a: "Look for denominator effects, timing, accounting classification, one-off items, leverage or a change in assumptions." },
          { q: "Write down the two or three numbers you would need to calculate or assess " + esc(title) + ".", a: "Use the definition first. Identify the numerator, denominator or operating drivers before reaching for a formula." },
          { q: "What would you compare " + esc(title) + " with before making an investment or transaction decision?", a: "Compare history, peers, management guidance, the business model and the assumptions behind the number." },
          { q: "Give a one-sentence investment-banking or investing interpretation of " + esc(title) + ".", a: "State what changed, why it changed, and whether the change improves or weakens the economic story." }
        ] },
        { t: "h2", text: "Sandbox" },
        { t: "sandbox", title: esc(title) + " — change the assumptions", prompt: "Change the inputs, predict the direction first, then explain the result in one sentence.", kind: "opportunity", fields: [
          { key: "amount", label: "Capital", value: 1000000, unit: "₹" },
          { key: "chosenReturn", label: "Scenario A", value: 12, unit: "%" },
          { key: "alternativeReturn", label: "Scenario B", value: 10, unit: "%" }
        ] },
        { t: "h2", text: "Check your understanding" },
        { t: "mcq", q: "What is the best first step when analysing " + esc(title) + "?", opts: ["Memorise a benchmark", "Define what it measures and identify its inputs", "Ignore the denominator", "Look only at the latest period"], correct: 1, why: ["A benchmark is useful only after the metric is understood.", "Correct. Start with the definition and inputs before calculating or comparing.", "The denominator often changes the interpretation materially.", "A single period rarely explains the economics."] },
        { t: "mcq", q: "Which approach gives the strongest finance explanation of " + esc(title) + "?", opts: ["State the number only", "State the number and explain what drove it", "Use a larger number because it sounds better", "Avoid assumptions"], correct: 1, why: ["A number without interpretation is incomplete.", "Correct. Finance is about linking the output to drivers and decisions.", "Magnitude alone does not establish quality.", "Good analysis makes assumptions explicit."] },
        { t: "mcq", q: "What should you do when a result looks unusually strong?", opts: ["Accept it immediately", "Check definitions, timing, one-offs and underlying drivers", "Delete the result", "Use a different currency"], correct: 1, why: ["Strong results still require verification.", "Correct. Unusual results deserve a driver and quality check.", "Unexpected results are often where the best analysis begins.", "Currency conversion does not solve an interpretation problem."] },
        { t: "h2", text: "Apply it in the real world" },
        { t: "note", h: "<strong>Mini case.</strong> You are preparing a company review and " + esc(title) + " has moved materially year over year. Before writing your conclusion, trace the movement back to the underlying business drivers, accounting treatment and assumptions. Then write a two-sentence conclusion: what changed, and whether you believe it is durable." },
        { t: "h2", text: "Common mistakes" },
        { t: "p", h: "<ul><li>Using the metric without checking its definition.</li><li>Ignoring the denominator or the timing of the inputs.</li><li>Confusing a reported result with an economic explanation.</li><li>Comparing businesses with different accounting or business models without adjustment.</li></ul>" },
        { t: "h2", text: "Master" },
        { t: "note", h: "<strong>Interview challenge:</strong> Explain " + esc(title) + " in 30 seconds, give a simple ₹ example, and name one reason the metric could mislead you." },
        { t: "note", h: "<strong>Key takeaway:</strong> Learn the definition → see it in a business → calculate it → test the assumptions → explain what the result means." }
      ]
    };
  }

  var used = {};
  LS.curriculumMap.forEach(function (lv) {
    lv.modules.forEach(function (mod) {
      mod.topics.forEach(function (topic) {
        var oldId = topic.id;
        var id = uniqueId(lv.level, mod.title, topic.title);
        if (used[id]) id += "-" + (used[id] + 1);
        used[id] = (used[id] || 0) + 1;

        var lesson = LS.lessons[oldId] || findExisting(topic.title);
        if (!lesson) lesson = fallbackLesson(id, topic.title, mod.title, lv.level);
        if (!LS.lessons[id]) {
          var copy = {};
          Object.keys(lesson).forEach(function (k) { copy[k] = lesson[k]; });
          copy.id = id;
          copy.title = topic.title;
          copy.short = lesson.short || topic.title;
          copy.desc = copy.desc || "Learn " + topic.title + " through explanation, examples and practice.";
          LS.lessons[id] = copy;
        }
        topic.id = id;
        topic.written = true;
        if (oldId && oldId !== id && !LS.lessons[oldId]) LS.lessons[oldId] = LS.lessons[id];
      });
    });
  });

  /* Keep the legacy fixed-income route alive while the curriculum moves to
     deterministic topic-l9-fixed-income-convexity URLs. */
  var convexity = null;
  LS.curriculumMap.some(function (lv) {
    return lv.modules.some(function (mod) {
      return mod.topics.some(function (topic) {
        if (topic.title === "Convexity" && lv.level === 9) {
          convexity = topic.id;
          return true;
        }
        return false;
      });
    });
  });
  if (convexity && LS.lessons[convexity]) {
    LS.lessons["9-fixed-income-convexity"] = LS.lessons[convexity];
  }
})();
